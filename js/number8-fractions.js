// Обычное математическое отображение дробей в №8: числитель над знаменателем.
(function(){
  const F=(a,b)=>`<span class="mfrac"><span>${a}</span><span>${b}</span></span>`;
  function convert(s){
    s=String(s||'');
    // Дроби в скобках: (1/2), (1/3) и т. п.
    s=s.replace(/\((\d+)\s*\/\s*(\d+)\)/g,(_,a,b)=>`(${F(a,b)})`);
    // 1/(выражение)
    s=s.replace(/\b1\s*\/\s*\(([^()]+)\)/g,(_,b)=>F('1',b));
    // Число или выражение в скобках, делённое на число/корень/выражение в скобках.
    s=s.replace(/(\([^()]+\)(?:<sup>[^<]+<\/sup>|²)?|\d+(?:<sup>[^<]+<\/sup>)?|√\d+)\s*\/\s*(\([^()]+\)(?:<sup>[^<]+<\/sup>|²)?|√\d+|\d+(?:<sup>[^<]+<\/sup>)?)/g,(_,a,b)=>F(a,b));
    // Последняя дробная черта в произведениях степеней/корней: весь левый множительный блок — числитель.
    s=s.replace(/((?:[\w√−]+(?:<sup>[^<]+<\/sup>)?)(?:\s*[·]\s*[\w√−]+(?:<sup>[^<]+<\/sup>)?)+)\s*\/\s*([\w√−]+(?:<sup>[^<]+<\/sup>)?)/g,(_,a,b)=>F(a,b));
    return s;
  }
  tasks.filter(t=>t.number===8).forEach(t=>{t.text=convert(t.text);});
})();